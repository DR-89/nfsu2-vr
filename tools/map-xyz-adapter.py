#!/usr/bin/env python3
"""Read-only PC/Xbox function comparison for the native multiplayer adapter.

Produces candidates, never patches game data or treats a similarity as a verified
address. Requires the supported owned executables and local Capstone. The Xbox
function inventory is generated by xboxrecomp; no game bytes are emitted.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import struct

from capstone import Cs, CS_ARCH_X86, CS_MODE_32
from capstone.x86 import X86_OP_IMM, X86_OP_MEM, X86_OP_REG, X86_REG_EBP, X86_REG_ESP

ROOT = Path(__file__).resolve().parents[1]
PC_HASH = 'f9dd86c054878ce6276beb07c1fd61874f7a1e4bf1f241b084c65b73e24168a7'
XBOX_HASH = 'c8cab1bfe7cf26553e84eb4ef2a26d16f6b06260f7494c583802bc00fd81dd31'


def checked(path, digest):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f'Unsupported executable: {path.name}')
    return data


def pc_offset(data, address):
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    n = struct.unpack_from('<H', data, pe + 6)[0]
    opt = struct.unpack_from('<H', data, pe + 20)[0]
    base = struct.unpack_from('<I', data, pe + 52)[0]
    for i in range(n):
        _, va, size, raw = struct.unpack_from('<4I', data, pe + 24 + opt + 40 * i + 8)
        if va <= address - base < va + size:
            return raw + address - base - va
    raise ValueError(f'Unmapped PC address: {address:x}')


def pc_instructions(disassembler, data, start):
    """Walk local control flow; never consume the next function's padding/code.

    Direct tail calls outside the 4 KiB window and calls are not followed.
    MSVC's absolute switch tables are followed only while entries point to code
    between this entry point and the table. Exception metadata is not code.
    """
    pending, instructions = [start], {}
    while pending:
        address = pending.pop()
        while start <= address < start + 4096 and address not in instructions:
            offset = pc_offset(data, address)
            ins = next(disassembler.disasm(data[offset:offset + 16], address, count=1), None)
            if ins is None or ins.mnemonic in ('int3', 'ud2'):
                break
            instructions[address] = ins
            if ins.mnemonic.startswith('ret'):
                break
            if ins.mnemonic.startswith('j'):
                op = ins.operands[0]
                if op.type == X86_OP_IMM:
                    pending.append(op.imm)
                elif ins.mnemonic == 'jmp' and op.type == X86_OP_MEM and op.mem.index and not op.mem.base and op.mem.scale == 4:
                    table = op.mem.disp
                    try:
                        base = pc_offset(data, table)
                        for i in range(32):
                            target = struct.unpack_from('<I', data, base + i * 4)[0]
                            if not start <= target < min(table, start + 4096):
                                break
                            pending.append(target)
                    except ValueError:
                        pass
                if ins.mnemonic == 'jmp':
                    break
            address += ins.size
    return [ins for _, ins in sorted(instructions.items())]


def signature(disassembler, data, address, instructions=None):
    result = []
    for ins in instructions if instructions is not None else disassembler.disasm(data, address):
        if ins.mnemonic == 'int3':
            break
        operands = []
        for op in ins.operands:
            if op.type == X86_OP_REG:
                operands.append('R')
            elif op.type == X86_OP_MEM:
                m = op.mem
                # The Xbox compiler uses EBP frames while PC often uses ESP.
                if m.base in (X86_REG_EBP, X86_REG_ESP):
                    operands.append('STACK')
                elif not m.base and not m.index:
                    operands.append('GLOBAL')
                else:
                    operands.append(f'M:{m.disp:x}:{m.scale}:{bool(m.index)}')
            elif op.type == X86_OP_IMM:
                if ins.mnemonic.startswith('j') or ins.mnemonic == 'call':
                    operands.append('TARGET')
                else:
                    operands.append(str(op.imm) if -65536 <= op.imm <= 65535 else 'ADDR/CONST')
        result.append(ins.mnemonic + ':' + ','.join(operands))
    return result


def grams(seq):
    return Counter(tuple(seq[i:i + 3]) for i in range(len(seq) - 2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pc-game', required=True, type=Path)
    parser.add_argument('--xbox', type=Path, default=ROOT / 'game/default.xbe')
    parser.add_argument('--functions', type=Path, default=ROOT / 'xboxrecomp/tools/disasm/output/functions.json')
    parser.add_argument('--upstream', type=Path, default=ROOT / 'upstream/nfsu2-web')
    parser.add_argument('--name', action='append', help='FN_ define to compare; repeatable')
    parser.add_argument('--all', action='store_true', help='Compare every FN_ in the reference adapter')
    parser.add_argument('--address', action='append', default=[], help='Additional comparison LABEL=0xPC_ADDRESS; repeatable')
    args = parser.parse_args()
    try:
        pc = checked(args.pc_game / 'SPEED2.EXE' if args.pc_game.is_dir() else args.pc_game, PC_HASH)
        xbox = checked(args.xbox, XBOX_HASH)
        definitions = (args.upstream / 'runtime/roam_game.c').read_text(encoding='utf-8')
        targets = dict(re.findall(r'^#define\s+(FN_\w+)\s+(0x[0-9a-fA-F]+)u', definitions, re.M))
        extra = {}
        for item in args.address:
            found = re.fullmatch(r'([A-Z][A-Z0-9_]+)=(0x[0-9a-fA-F]{1,8})', item)
            if not found:
                raise ValueError('An additional address must be LABEL=0xPC_ADDRESS')
            extra[found[1]] = found[2]
        targets.update(extra)
        selected = list(targets) if args.all else args.name or list(extra) or ['FN_CREATECAR', 'FN_CAR_SETDRIVER', 'FN_INDEXCARS', 'FN_CAR_SETRIDE', 'FN_TYPE_BY_HASH', 'FN_RIDE_INIT']
        if any(name not in targets for name in selected):
            raise ValueError('Unknown function define')
        dis = Cs(CS_ARCH_X86, CS_MODE_32)
        dis.detail = True
        candidates = []
        for f in json.loads(args.functions.read_text()):
            a, end = int(f['start'], 16), int(f['end'], 16)
            # Original supported XBE .text raw = VA - 0x10000. Exclude kernel,
            # assets and virtual tail data. These bounds are not runtime checks.
            if f['section'] != '.text' or a < 0x11000 or end > 0x2a0000 or end - a < 12:
                continue
            sig = signature(dis, xbox[a - 0x10000:end - 0x10000], a)
            g = grams(sig)
            if g:
                candidates.append((a, end, g))
        report = {'status': 'candidates_only_not_runtime_verified', 'pc_sha256': PC_HASH,
                  'xbox_sha256': XBOX_HASH, 'matches': {}}
        for name in selected:
            a = int(targets[name], 16)
            target = grams(signature(dis, b'', a, pc_instructions(dis, pc, a)))
            scored = []
            for start, end, candidate in candidates:
                common = sum((target & candidate).values())
                if not common:
                    continue
                # Dice coefficient: large generic functions must not win merely
                # because they contain many of the same instructions.
                score = 2 * common / (sum(target.values()) + sum(candidate.values()))
                scored.append((score, common, start, end))
            report['matches'][name] = {'pc': f'0x{a:08x}', 'candidates': [
                {'xbox': f'0x{s:08x}', 'end': f'0x{e:08x}', 'similarity': round(score, 4), 'shared_trigrams': common}
                for score, common, s, e in sorted(scored, reverse=True)[:3]]}
        print(json.dumps(report, indent=2))
    except (OSError, ValueError, KeyError) as error:
        parser.error(str(error))


if __name__ == '__main__':
    main()
